const designMatchesProductIdentity = (design, product) => {
  const productId = String(product?.id || "");
  const slug = String(product?.slug || "");
  return (
    design.productId === productId ||
    (Array.isArray(design.slugs) && design.slugs.includes(slug))
  );
};

const designMatchesProductFamily = (design, product) => {
  if (!design.familyCategory) return true;
  const categories = [product?.subCategory, product?.subcategory]
    .map((value) => String(value || "").trim().toLowerCase());
  return categories.includes(String(design.familyCategory).toLowerCase());
};

export const coloringDesignForProduct = (product) => {
  return COLORING_DESIGNS.find((design) =>
    design.enabled !== false &&
    designMatchesProductIdentity(design, product) &&
    designMatchesProductFamily(design, product)
  ) || null;
};

export const coloringDesignById = (modelId) =>
  COLORING_DESIGNS.find((design) => design.id === modelId) || null;

export const coloringDesignStatusForProduct = (product) => {
  return COLORING_DESIGNS.find((design) => designMatchesProductIdentity(design, product)) || null;
};

const withoutColoringConfig = (product) => {
  const {
    coloringModelId,
    coloringModelName,
    coloringModelVersion,
    coloringBaseImageUrl,
    coloringMaskUrl,
    coloringOutlineUrl,
    coloringRegionsUrl,
    coloringRegionOverridesUrl,
    coloringRegions,
    shapeGroups,
    ...cleanProduct
  } = product || {};
  return cleanProduct;
};

export const withYotaColoringConfig = (product) => {
  const status = coloringDesignStatusForProduct(product);
  if (!status) return product;

  // Yota products can be duplicated in the catalog together with stale
  // coloring fields. Always clear those fields before selecting by the real
  // product ID, so one model can never display another model's artwork/mask.
  const cleanProduct = withoutColoringConfig(product);
  if (status.enabled === false || !designMatchesProductFamily(status, product)) return cleanProduct;

  const version = encodeURIComponent(status.assetVersion || status.modelVersion);
  const assetUrl = (assetPath) => status.omitAssetVersion ? assetPath : `${assetPath}?v=${version}`;
  return {
    ...cleanProduct,
    coloringModelId: status.id,
    coloringModelName: status.name,
    coloringModelVersion: status.modelVersion,
    coloringBaseImageUrl: assetUrl(status.basePath),
    coloringMaskUrl: assetUrl(status.regionsPath),
    coloringOutlineUrl: assetUrl(status.outlinePath),
    coloringRegionsUrl: assetUrl(status.regionsDataPath),
    ...(status.regionOverridesPath
      ? { coloringRegionOverridesUrl: assetUrl(status.regionOverridesPath) }
      : {})
  };
};
